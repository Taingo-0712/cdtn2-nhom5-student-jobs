CREATE TABLE public.job_posts (
    job_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- ID tin tự sinh.
    employer_id BIGINT NOT NULL
        REFERENCES public.employer_profiles(user_id) ON DELETE RESTRICT, -- Chủ tin.
    category_id BIGINT NOT NULL
        REFERENCES public.job_categories(category_id) ON DELETE RESTRICT, -- Danh mục tin.
    title VARCHAR(200) NOT NULL CHECK (btrim(title) <> ''), -- Tiêu đề bắt buộc.
    description TEXT NOT NULL CHECK (btrim(description) <> ''), -- Mô tả công việc.
    work_time TEXT NOT NULL CHECK (btrim(work_time) <> ''), -- Lịch hoặc ca làm.
    salary_min NUMERIC(12, 2) NOT NULL CHECK (salary_min >= 0), -- Lương tối thiểu.
    salary_max NUMERIC(12, 2) NOT NULL CHECK (salary_max >= salary_min), -- Lương tối đa.
    salary_unit VARCHAR(10) NOT NULL
        CHECK (salary_unit IN ('HOUR', 'DAY', 'SHIFT', 'MONTH')), -- Đơn vị tính lương.
    city VARCHAR(100) NOT NULL CHECK (btrim(city) <> ''), -- Tỉnh hoặc thành phố.
    location_detail VARCHAR(255) NOT NULL CHECK (btrim(location_detail) <> ''), -- Địa chỉ cụ thể.
    status VARCHAR(16) NOT NULL DEFAULT 'RECRUITING'
        CHECK (status IN ('RECRUITING', 'FILLED', 'COMPLETED')), -- Tin mới đang tuyển.
    completed_at TIMESTAMPTZ, -- Thời điểm hoàn thành cả đợt tuyển.
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, -- Thời điểm tạo tin.
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, -- Thời điểm cập nhật.
    CONSTRAINT chk_job_posts_completed_at CHECK (
        (status = 'COMPLETED' AND completed_at IS NOT NULL AND completed_at >= created_at)
        OR (status IN ('RECRUITING', 'FILLED') AND completed_at IS NULL)
    ) -- Chỉ tin đã hoàn thành mới có thời điểm hoàn thành.
);
