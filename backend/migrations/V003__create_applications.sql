CREATE TABLE public.applications (
    application_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id BIGINT NOT NULL
        REFERENCES public.job_posts(job_id) ON DELETE RESTRICT,
    student_id BIGINT NOT NULL
        REFERENCES public.student_profiles(user_id) ON DELETE RESTRICT,
    status VARCHAR(16) NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED')),
    cv_storage_key VARCHAR(255) NOT NULL UNIQUE,
    cv_original_name VARCHAR(255) NOT NULL
        CHECK (btrim(cv_original_name) <> ''),
    cv_mime_type VARCHAR(100) NOT NULL
        CHECK (cv_mime_type = 'application/pdf'),
    cv_size_bytes INTEGER NOT NULL
        CHECK (cv_size_bytes BETWEEN 1 AND 5242880),
    applied_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    decided_at TIMESTAMPTZ,
    CONSTRAINT uq_applications_student_job UNIQUE (student_id, job_id),
    CONSTRAINT chk_applications_decided_at CHECK (
        (status = 'PENDING' AND decided_at IS NULL)
        OR (
            status IN ('APPROVED', 'REJECTED')
            AND decided_at IS NOT NULL
            AND decided_at >= applied_at
        )
    )
);
