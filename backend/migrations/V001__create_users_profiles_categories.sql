-- Tài khoản dùng chung cho các vai trò.
CREATE TABLE public.users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- ID tự sinh.
    email VARCHAR(254) NOT NULL UNIQUE, -- Email bắt buộc và duy nhất.
    password_hash VARCHAR(255) NOT NULL, -- Lưu giá trị băm của mật khẩu.
    role VARCHAR(16) NOT NULL, -- Vai trò lấy từ tài khoản.
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, -- Thời điểm tạo.
    CONSTRAINT chk_users_email_normalized
        CHECK (email <> '' AND email = lower(btrim(email))), -- Email đã trim và viết thường.
    CONSTRAINT chk_users_role
        CHECK (role IN ('STUDENT', 'EMPLOYER', 'ADMIN')) -- Ba vai trò theo schema.
);

-- Hồ sơ sinh viên dùng chung ID với tài khoản.
CREATE TABLE public.student_profiles (
    user_id BIGINT PRIMARY KEY REFERENCES public.users(user_id) ON DELETE RESTRICT,
    full_name VARCHAR(150) NOT NULL CHECK (btrim(full_name) <> ''), -- Họ tên bắt buộc.
    phone VARCHAR(11) CHECK (phone IS NULL OR phone ~ '^[0-9]{10,11}$'), -- Nếu có, gồm 10–11 số.
    introduction TEXT, -- Giới thiệu tùy chọn.
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP -- Thời điểm cập nhật ban đầu.
);

-- Hồ sơ nhà tuyển dụng cũng dùng chung ID với tài khoản.
CREATE TABLE public.employer_profiles (
    user_id BIGINT PRIMARY KEY REFERENCES public.users(user_id) ON DELETE RESTRICT,
    display_name VARCHAR(200) NOT NULL CHECK (btrim(display_name) <> ''), -- Tên hiển thị bắt buộc.
    contact_name VARCHAR(150), -- Người liên hệ tùy chọn.
    phone VARCHAR(11) CHECK (phone IS NULL OR phone ~ '^[0-9]{10,11}$'), -- Cùng quy tắc số điện thoại.
    introduction TEXT, -- Giới thiệu tùy chọn.
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP -- Thời điểm cập nhật ban đầu.
);

-- Danh mục mà nhà tuyển dụng chọn khi đăng tin.
CREATE TABLE public.job_categories (
    category_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- ID danh mục tự sinh.
    name VARCHAR(100) NOT NULL UNIQUE CHECK (btrim(name) <> '') -- Tên có nội dung và duy nhất.
);
